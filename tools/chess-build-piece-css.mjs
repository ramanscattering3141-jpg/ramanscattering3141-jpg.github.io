// Writes src/chess/ui/pieces.css: Chessground piece images (cburnett, GPLv2+) as data URIs.
import { readFileSync, writeFileSync } from 'node:fs';
const names = { K: 'king', Q: 'queen', R: 'rook', B: 'bishop', N: 'knight', P: 'pawn' };
let css = '/* Pieces: cburnett by Colin M.L. Burnett, GPLv2+ (via lichess.org). Generated by tools/chess-build-piece-css.mjs */\n';
for (const set of ['cburnett', 'merida']) for (const c of ['w', 'b']) for (const [k, n] of Object.entries(names)) {
  const svg = readFileSync(`tools/chess-pieces/${set}/${c}${k}.svg`);
  css += `.pieces-${set} .cg-wrap piece.${n}.${c === 'w' ? 'white' : 'black'},.pieces-${set} .pc-${c}${k}{background-image:url('data:image/svg+xml;base64,${svg.toString('base64')}')}\n`;
}
writeFileSync('src/chess/ui/pieces.css', css);
