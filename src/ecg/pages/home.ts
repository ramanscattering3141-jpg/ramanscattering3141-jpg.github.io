import { h, p } from '../ui/dom';
import { header, loopBanner, presetPhysio } from '../ui/common';
import { EcgPanel } from '../ui/panel';
import { ALL_DX } from '../content/index';
import { EPONYMS } from '../content/eponyms';
import { SOURCES } from '../content/sources';

type Tile = [string, string, string, string]; // [badge, title, href, description]

function tiles(list: Tile[]): HTMLElement {
  return h('div', { class: 'grid' }, ...list.map(([l, t, href, d]) => h('a', { class: 'tile', href }, l ? h('span', { class: 'pill core' }, l) : null, h('h3', null, t), h('p', null, d))));
}

export function renderHome(root: HTMLElement): () => void {
  root.append(
    header('Physiology-first ECG education', 'Don’t memorise the ECG — predict it', 'Every tracing in this lab is generated by a conduction simulator: pacemaker cells, AV-nodal refractoriness, fast and slow pathways, accessory pathways, bundle branches, ventricular mass, ions, drugs and injury currents. Change the physiology, watch the ECG change, then explain why.'),
    loopBanner(),
  );

  const search = h('input', { type: 'search', placeholder: 'Search, e.g. “wide QRS” or “adenosine”', 'aria-label': 'Search the ECG lab', enterkeyhint: 'search' });
  search.addEventListener('keydown', (e) => {
    if (e.key === 'Enter' && search.value.trim()) location.hash = `#/search?q=${encodeURIComponent(search.value.trim())}`;
  });
  root.append(
    h(
      'section',
      { class: 'card' },
      h('h2', null, 'How to use this lab'),
      h(
        'ol',
        { class: 'start-steps' },
        h('li', null, p('**New to ECGs?** Follow the [learning path](#/path): twelve stages from ion channels to bedside management, with your progress saved in this browser.')),
        h('li', null, p('**Learning a diagnosis?** Open it from the [rhythm library](#/rhythms) or the [A–Z index](#/az). Every page has a live ECG generated from physiology, a “why does it look like this?” chain, the differential and mechanism-linked management.')),
        h('li', null, p('**Want to experiment?** The [simulator](#/simulator) and [physiology sandbox](#/sandbox) let you change one variable at a time and see exactly what the ECG does. The [heart simulator](#/heart3d) slows time down to 1/100 so you can watch each wave being written.')),
        h('li', null, p('**Ready to test yourself?** Try the [case generator](#/cases) and the five-level [challenge mode](#/challenge).')),
      ),
      h('div', { class: 'search-big' }, search),
    ),
  );

  const panel = new EcgPanel({ heart: true, duration: 8000, layout: 'strips', leads: ['II', 'V1'], showLadder: true, showLabels: true });
  root.append(h('section', { class: 'card' }, h('h2', null, 'Live example: a premature atrial beat starts AV nodal re-entry'), p('A premature atrial beat finds the **fast pathway** still refractory, travels down the **slow pathway** (a sudden jump in the PR interval) and returns up the recovered fast pathway — a re-entry circuit is born. Press **Play** (choose a slow speed, or step ±1 ms) and follow the ladder diagram under the ECG and the heart above it.'), panel.el));
  panel.show(presetPhysio('avnrt'));

  const sections: Tile[] = [
    ['A', 'ECG Fundamentals', '#/fundamentals', 'Membrane and action potentials, vectors, the 12 leads, a rotatable activation vector, and a systematic way to read any ECG.'],
    ['B', 'ECG Physiology', '#/physiology', 'Why each wave exists, ventricular activation millisecond by millisecond, and “why?” chains for every major finding.'],
    ['C', 'ECG Simulator', '#/simulator', 'Every physiological variable on a slider, with a live 12-lead, ladder diagram and conduction animation.'],
    ['D', 'Rhythm Library', '#/rhythms', 'Sinus, ectopic, atrial, junctional, re-entrant, ventricular and arrest rhythms, plus AVNRT, AVRT and flutter labs.'],
    ['E', 'Conduction Disorders', '#/conduction', 'AV block with selectable level and escape rhythm; bundle-branch and fascicular block step by step; pacemakers.'],
    ['F', 'Structural & Physiological', '#/structural', 'LVH, RVH, atrial enlargement, poor R progression, cardiomyopathies, pericardial and pulmonary patterns.'],
    ['G', 'Ischaemia & Infarction', '#/ischemia', 'Choose an artery, territory and stage; watch injury currents create ST elevation and reciprocal depression.'],
    ['H', 'Electrolytes & Toxicology', '#/electrolytes', 'Change K⁺, Ca²⁺ and Mg²⁺ continuously; digoxin, β-blockers, calcium-channel blockers, sodium-channel blockers and QT-prolonging drugs.'],
    ['I', 'Inherited & Electrical Syndromes', '#/inherited', 'Long and short QT, Brugada, early repolarisation and the cellular basis of each.'],
    ['J', 'Arrhythmia Management', '#/management', 'Recognition → mechanism → stable or unstable → immediate and definitive therapy → why it works (and why others do not).'],
    ['K', 'ACLS ECG Reference', '#/acls', '2025 AHA algorithms: cardiac arrest, tachycardia with a pulse and bradycardia with a pulse.'],
    ['L', 'ECG Cases', '#/cases', 'Randomised clinical cases with a step-by-step interpretation and a full explanation.'],
    ['M', 'ECG Challenge Mode', '#/challenge', 'Five levels: recognition → interpretation → mechanism → electrophysiology → management.'],
    ['N', 'Physiology Sandbox', '#/sandbox', 'Change one variable, build your own arrhythmia, the adenosine demonstrator, comparisons, and axis, P, QRS and ST labs.'],
  ];
  const interactive: Tile[] = [
    ['', 'Heart simulator', '#/heart3d', 'A beating 3-D heart run by the simulation: slow time to 1/100, step a millisecond at a time, and watch the impulse travel the conduction system as each wave of the ECG is written.'],
    ['', 'Differential diagnosis engine', '#/ddx', 'Start from what you see — narrow or wide, regular or irregular, ST elevation, dominant R in V1 — and compare the candidates.'],
    ['', 'Clinical tools & calculators', '#/tools', 'QTc (four formulas), CHA₂DS₂-VASc, Sgarbossa and Smith criteria, wide-complex tachycardia algorithms, lead reversal.'],
    ['', 'Learning path & progress', '#/path', 'A suggested order through the lab, with a checklist of every core diagnosis.'],
  ];
  const reference: Tile[] = [
    ['', 'ECG library A–Z', '#/az', `Every diagnosis, finding, named sign and glossary term in one alphabetical index (${ALL_DX.length} diagnoses).`],
    ['', 'Named signs & eponyms', '#/eponyms', `${EPONYMS.length} named signs, criteria and patterns — from Ashman to Wellens — each with its definition and source.`],
    ['', 'Normal values & variants', '#/normal', 'Adult reference values, what an abnormal value points to, and the normal variants most often mistaken for disease.'],
    ['', 'STEMI equivalents & mimics', '#/omi', 'Occlusion-MI patterns that miss the ST-elevation criteria, and the patterns that imitate them.'],
    ['', 'Glossary', '#/glossary', 'Core electrophysiology vocabulary, each term defined by mechanism.'],
    ['', 'Sources & evidence', '#/sources', `${Object.keys(SOURCES).length} guideline and journal sources, each checked against PubMed with a verification date.`],
  ];
  root.append(h('h2', null, 'Sections A–N'), tiles(sections), h('h2', null, 'Interactive tools'), tiles(interactive), h('h2', null, 'Reference'), tiles(reference));
  root.append(
    h(
      'section',
      { class: 'card' },
      h('h2', null, 'How the model works'),
      p('1. **Rhythm engine** — an event-driven network of excitable elements (sinus node, atria, AV-nodal fast and slow pathways, His bundle, bundle branches, accessory pathway, ventricles, escape foci, pacemaker). Each has a conduction time and a refractory period; blocked impulses can be concealed and opposing wavefronts collide. Re-entry, Wenckebach periodicity, AV dissociation, fusion and the responses to adenosine emerge from these rules rather than being drawn.'),
      p('2. **Waveform engine** — each activation or repolarisation is a set of dipole components (direction, strength, timing) based on the normal activation sequence (Durrer 1970) and its modification by conduction abnormalities, chamber mass, ions, drugs and injury. Each lead records the projection of the summed heart vector on its axis.'),
      p(`3. **Content database** — ${ALL_DX.length} diagnosis records with definition, mechanism, ECG findings, “why?” chains, differential diagnosis, management and verified references (ACC/AHA/HRS, ESC, AHA 2025 ACLS, CCS).`),
      p('ECGs are printed at the standard **25 mm/s and 10 mm/mV** on a 1 mm / 5 mm grid, with a 1 mV calibration pulse at the start of each row. Drag across any tracing to measure an interval with the on-screen calipers.'),
    ),
  );
  return () => panel.destroy();
}
